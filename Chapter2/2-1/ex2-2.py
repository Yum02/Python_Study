print("He"+"llo") #문자열을 더할 수 있다.
print("Hi"*3) #문자열을 곱할 수 있다.
#문자열과 숫자는 연산자 불가능하다

print("HELLO"[0])
print("HELLO"[1])
print("HELLO"[2])
print("HELLO"[3])
print("HELLO"[4])
#문자열의 인덱스는 0부터 시작한다.

print("HELLO"[-1])
print("HELLO"[-2])
print("HELLO"[-3])
print("HELLO"[-4])
print("HELLO"[-5])
#음수도 가능하다.

print("HELLO"[1:4])
#문자열 범위 선택 연산자인 슬라이싱을 사용하여 출력하고자 하는 범위 지정하여 출력가능하다.

print(len("HELLO"))
#문자열의 길이를 구하는 함수인 len()을 사용하여 문자열의 길이를 구할 수 있다.